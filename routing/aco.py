"""
Custom Ant Colony Optimization router.

This implementation is intentionally written from scratch so that every
important ACO mechanism can be explained during a viva.

The algorithm operates on routing costs generated by the fuzzy inference
system.

ACO components implemented here:

    - pheromone initialization
    - alpha: pheromone importance
    - beta: heuristic importance
    - probabilistic next-node selection
    - ant path construction
    - iteration-best path
    - global-best path
    - pheromone evaporation
    - global pheromone deposition
    - pheromone minimum/maximum bounds
    - reproducible random seed
    - convergence history
    - disconnected-network handling

The heuristic is:

    heuristic(edge) = 1 / edge_cost

Therefore:

    lower cost -> higher heuristic value
    higher cost -> lower heuristic value

The transition probability is proportional to:

    pheromone^alpha * heuristic^beta
"""

from __future__ import annotations

import random
from dataclasses import dataclass
from typing import Callable

import networkx as nx

from fuzzy.inference import calculate_link_cost
from simulator.graph_builder import get_active_graph


@dataclass
class ACOResult:
    """
    Result returned by the ACO router.
    """

    path: list[int]
    cost: float
    exists: bool
    convergence_history: list[float]
    iterations: int


class AntColonyOptimizer:
    """
    Custom Ant Colony Optimization router.

    Parameters
    ----------
    alpha:
        Importance of pheromone information.

    beta:
        Importance of heuristic information.

    evaporation_rate:
        Fraction of pheromone evaporated after each iteration.

    num_ants:
        Number of ants constructing routes per iteration.

    num_iterations:
        Number of optimization iterations.

    initial_pheromone:
        Initial pheromone value on every active edge.

    min_pheromone:
        Lower pheromone bound.

    max_pheromone:
        Upper pheromone bound.

    seed:
        Random seed for reproducibility.
    """

    def __init__(
        self,
        alpha: float = 1.0,
        beta: float = 2.0,
        evaporation_rate: float = 0.5,
        num_ants: int = 20,
        num_iterations: int = 50,
        initial_pheromone: float = 1.0,
        min_pheromone: float = 0.01,
        max_pheromone: float = 10.0,
        seed: int = 42,
    ) -> None:

        if alpha < 0:
            raise ValueError("alpha must be >= 0.")

        if beta < 0:
            raise ValueError("beta must be >= 0.")

        if not 0.0 <= evaporation_rate <= 1.0:
            raise ValueError(
                "evaporation_rate must be between 0 and 1."
            )

        if num_ants <= 0:
            raise ValueError("num_ants must be greater than 0.")

        if num_iterations <= 0:
            raise ValueError("num_iterations must be greater than 0.")

        if initial_pheromone <= 0:
            raise ValueError("initial_pheromone must be greater than 0.")

        if min_pheromone <= 0:
            raise ValueError("min_pheromone must be greater than 0.")

        if max_pheromone < min_pheromone:
            raise ValueError(
                "max_pheromone must be >= min_pheromone."
            )

        self.alpha = alpha
        self.beta = beta
        self.evaporation_rate = evaporation_rate
        self.num_ants = num_ants
        self.num_iterations = num_iterations

        self.initial_pheromone = initial_pheromone
        self.min_pheromone = min_pheromone
        self.max_pheromone = max_pheromone

        self.seed = seed
        self.rng = random.Random(seed)

        # Pheromone trails are stored using canonical undirected edges.
        self.pheromone: dict[tuple[int, int], float] = {}

        # Edge routing costs are recalculated when routing begins.
        self.edge_costs: dict[tuple[int, int], float] = {}

    # -----------------------------------------------------------------------
    # Edge helpers
    # -----------------------------------------------------------------------

    @staticmethod
    def _edge_key(u: int, v: int) -> tuple[int, int]:
        """
        Return a canonical edge key.

        The network is undirected, so (u, v) and (v, u) must share
        the same pheromone value.
        """

        return (u, v) if u <= v else (v, u)

    # -----------------------------------------------------------------------
    # Cost calculation
    # -----------------------------------------------------------------------

    def _calculate_edge_costs(
        self,
        graph: nx.Graph,
    ) -> None:
        """
        Calculate fuzzy-derived cost for every active edge.

        The exact same fuzzy quality -> cost conversion used by the
        Dijkstra fuzzy baseline is used here.
        """

        self.edge_costs.clear()

        for u, v, data in graph.edges(data=True):

            _, cost = calculate_link_cost(
                latency=data["latency"],
                packet_loss=data["packet_loss"],
                bandwidth=data["bandwidth"],
                congestion=data["congestion"],
            )

            self.edge_costs[self._edge_key(u, v)] = float(cost)

    # -----------------------------------------------------------------------
    # Pheromone initialization
    # -----------------------------------------------------------------------

    def _initialize_pheromones(
        self,
        graph: nx.Graph,
    ) -> None:
        """
        Initialize pheromone trails.

        Existing pheromone values are preserved when possible. This is
        useful for the dashboard because the ACO can retain learned
        information between rerouting events.
        """

        new_pheromone: dict[tuple[int, int], float] = {}

        for u, v in graph.edges():
            key = self._edge_key(u, v)

            if key in self.pheromone:
                value = self.pheromone[key]
            else:
                value = self.initial_pheromone

            new_pheromone[key] = min(
                self.max_pheromone,
                max(self.min_pheromone, value),
            )

        self.pheromone = new_pheromone

    # -----------------------------------------------------------------------
    # Heuristic
    # -----------------------------------------------------------------------

    def _heuristic(
        self,
        u: int,
        v: int,
    ) -> float:
        """
        Calculate heuristic desirability for an edge.

        Lower routing cost means higher heuristic value.
        """

        key = self._edge_key(u, v)
        cost = self.edge_costs[key]

        return 1.0 / max(cost, 1e-12)

    # -----------------------------------------------------------------------
    # Next-node selection
    # -----------------------------------------------------------------------

    def _choose_next_node(
        self,
        current: int,
        candidates: list[int],
    ) -> int:
        """
        Select the next node using the ACO transition rule.

        Probability is proportional to:

            pheromone^alpha * heuristic^beta

        If numerical problems occur, the method falls back to
        uniform random selection among valid candidates.
        """

        if not candidates:
            raise ValueError("No candidate nodes available.")

        weighted_candidates: list[tuple[int, float]] = []

        for candidate in candidates:

            key = self._edge_key(current, candidate)

            pheromone = self.pheromone.get(
                key,
                self.initial_pheromone,
            )

            heuristic = self._heuristic(
                current,
                candidate,
            )

            score = (
                pheromone ** self.alpha
                * heuristic ** self.beta
            )

            weighted_candidates.append(
                (candidate, score)
            )

        total_score = sum(
            score
            for _, score in weighted_candidates
        )

        if total_score <= 0 or not float(total_score) == total_score:
            return self.rng.choice(candidates)

        probabilities = [
            score / total_score
            for _, score in weighted_candidates
        ]

        # random.choices performs weighted probabilistic selection.
        return self.rng.choices(
            [node for node, _ in weighted_candidates],
            weights=probabilities,
            k=1,
        )[0]

    # -----------------------------------------------------------------------
    # Ant path construction
    # -----------------------------------------------------------------------

    def _construct_ant_path(
        self,
        graph: nx.Graph,
        source: int,
        destination: int,
    ) -> tuple[list[int], float] | None:
        """
        Construct one ant's path.

        An ant cannot visit the same node twice. This prevents cycles.

        If the ant becomes trapped before reaching the destination,
        None is returned.
        """

        path = [source]
        visited = {source}

        current = source

        # Maximum number of nodes visited by a simple path.
        max_steps = graph.number_of_nodes()

        for _ in range(max_steps):

            if current == destination:
                break

            candidates = [
                neighbor
                for neighbor in graph.neighbors(current)
                if neighbor not in visited
            ]

            if not candidates:
                return None

            next_node = self._choose_next_node(
                current,
                candidates,
            )

            path.append(next_node)
            visited.add(next_node)
            current = next_node

            if current == destination:
                break

        if current != destination:
            return None

        cost = self._path_cost(path)

        return path, cost

    # -----------------------------------------------------------------------
    # Path cost
    # -----------------------------------------------------------------------

    def _path_cost(
        self,
        path: list[int],
    ) -> float:
        """Calculate total fuzzy-derived cost of a path."""

        if len(path) < 2:
            return 0.0

        total = 0.0

        for u, v in zip(path, path[1:]):
            total += self.edge_costs[
                self._edge_key(u, v)
            ]

        return float(total)

    # -----------------------------------------------------------------------
    # Pheromone evaporation
    # -----------------------------------------------------------------------

    def _evaporate_pheromone(self) -> None:
        """
        Apply global pheromone evaporation.

        Formula:

            tau_new = (1 - rho) * tau_old

        where rho is the evaporation rate.

        Pheromone values are then bounded to [min, max].
        """

        for key, value in self.pheromone.items():

            new_value = (
                (1.0 - self.evaporation_rate)
                * value
            )

            self.pheromone[key] = min(
                self.max_pheromone,
                max(self.min_pheromone, new_value),
            )

    # -----------------------------------------------------------------------
    # Global pheromone update
    # -----------------------------------------------------------------------

    def _deposit_pheromone(
        self,
        path: list[int],
        cost: float,
    ) -> None:
        """
        Deposit pheromone on the supplied path.

        Global update rule:

            delta_tau = 1 / path_cost

        Better paths therefore receive more pheromone.
        """

        if not path or cost <= 0:
            return

        deposit = 1.0 / cost

        for u, v in zip(path, path[1:]):

            key = self._edge_key(u, v)

            if key not in self.pheromone:
                continue

            new_value = (
                self.pheromone[key]
                + deposit
            )

            self.pheromone[key] = min(
                self.max_pheromone,
                max(self.min_pheromone, new_value),
            )

    # -----------------------------------------------------------------------
    # Main optimization method
    # -----------------------------------------------------------------------

    def find_route(
        self,
        graph: nx.Graph,
        source: int,
        destination: int,
    ) -> ACOResult:
        """
        Find a route using Ant Colony Optimization.

        Returns:
            ACOResult containing:

                path
                cost
                exists
                convergence_history
                iterations
        """

        if source not in graph:
            raise ValueError(
                f"Source node {source} does not exist."
            )

        if destination not in graph:
            raise ValueError(
                f"Destination node {destination} does not exist."
            )

        if not graph.nodes[source].get("enabled", True):
            raise ValueError(
                f"Source node {source} is disabled."
            )

        if not graph.nodes[destination].get("enabled", True):
            raise ValueError(
                f"Destination node {destination} is disabled."
            )

        active_graph = get_active_graph(graph)

        # Explicit disconnected-network handling.
        if not nx.has_path(
            active_graph,
            source,
            destination,
        ):
            return ACOResult(
                path=[],
                cost=float("inf"),
                exists=False,
                convergence_history=[],
                iterations=0,
            )

        self._calculate_edge_costs(active_graph)

        self._initialize_pheromones(active_graph)

        convergence_history: list[float] = []

        global_best_path: list[int] | None = None
        global_best_cost = float("inf")

        for _iteration in range(self.num_iterations):

            iteration_best_path: list[int] | None = None
            iteration_best_cost = float("inf")

            for _ant in range(self.num_ants):

                result = self._construct_ant_path(
                    active_graph,
                    source,
                    destination,
                )

                if result is None:
                    continue

                path, cost = result

                # Tie-breaking rule:
                # If two paths have exactly equal cost, prefer fewer hops.
                if (
                    cost < iteration_best_cost
                    or (
                        cost == iteration_best_cost
                        and iteration_best_path is not None
                        and len(path) < len(iteration_best_path)
                    )
                ):
                    iteration_best_path = path
                    iteration_best_cost = cost

                if (
                    cost < global_best_cost
                    or (
                        cost == global_best_cost
                        and global_best_path is not None
                        and len(path) < len(global_best_path)
                    )
                ):
                    global_best_path = path
                    global_best_cost = cost

            # Record convergence even if no ant reached destination.
            convergence_history.append(
                float(global_best_cost)
            )

            # Global pheromone update:
            # 1. Evaporate
            # 2. Deposit on iteration-best path
            self._evaporate_pheromone()

            if iteration_best_path is not None:
                self._deposit_pheromone(
                    iteration_best_path,
                    iteration_best_cost,
                )

        if global_best_path is None:
            return ACOResult(
                path=[],
                cost=float("inf"),
                exists=False,
                convergence_history=convergence_history,
                iterations=self.num_iterations,
            )

        return ACOResult(
            path=global_best_path,
            cost=float(global_best_cost),
            exists=True,
            convergence_history=convergence_history,
            iterations=self.num_iterations,
        )